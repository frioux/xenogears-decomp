// RotMatrixZYX on: RotMatrixYXZ (the function before it) carries one tail pad
// word in retail, so the four bytes at 0x3B3B8 are an `asm` subsegment in
// config/slus_006.64.yaml and this file covers 0x3B3BC-0x3B648. See
// psyq/libgte_average_b.

extern long D_800523F0[]; // one entry per 1/4096 turn, (cos << 16) | sin

/* Sony's vector.s, transcribed like RotMatrixX: gcc emits `mult` where the
   original has `multu` and reads the trig table through its own registers.
   RotMatrixZYX and RotMatrixYXZ are the same routine with the three lookups
   (r->vx, r->vy, r->vz) and the nine products in a different order: each axis
   negates its own sine before the sign test picks a branch, and the products
   are accumulated as the matrix is filled. The epilogue `jr` is gcc's. */
MATRIX *RotMatrixZYX(SVECTOR *r, MATRIX *m) {
    register MATRIX *pRet __asm__("$2");

    __asm__ volatile (".set\tnoreorder\n\t"
                      "lh	$15, 0($4)\n\t"
                      "addu	$2, $5, $0\n\t"
                      "bgez	$15, .LRMZYXvxpos\n\t"
                      "andi	$25, $15, 4095\n\t"
                      "negu	$15, $15\n\t"
                      "bgez	$15, .LRMZYXvxneg\n\t"
                      "andi	$15, $15, 4095\n\t"
                      ".LRMZYXvxneg:\n\t"
                      "sll	$24, $15, 2\n\t"
                      "lui	$25, %%hi(D_800523F0)\n\t"
                      "addu	$25, $25, $24\n\t"
                      "lw	$25, %%lo(D_800523F0)($25)\n\t"
                      "nop\n\t"
                      "sll	$14, $25, 16\n\t"
                      "sra	$14, $14, 16\n\t"
                      "negu	$11, $14\n\t"
                      "j	.LRMZYXvxjoin\n\t"
                      "sra	$8, $25, 16\n\t"
                      ".LRMZYXvxpos:\n\t"
                      "sll	$24, $25, 2\n\t"
                      "lui	$25, %%hi(D_800523F0)\n\t"
                      "addu	$25, $25, $24\n\t"
                      "lw	$25, %%lo(D_800523F0)($25)\n\t"
                      "nop\n\t"
                      "sll	$24, $25, 16\n\t"
                      "sra	$11, $24, 16\n\t"
                      "sra	$8, $25, 16\n\t"
                      ".LRMZYXvxjoin:\n\t"
                      "lh	$15, 2($4)\n\t"
                      "nop\n\t"
                      "bgez	$15, .LRMZYXvypos\n\t"
                      "andi	$25, $15, 4095\n\t"
                      "negu	$15, $15\n\t"
                      "bgez	$15, .LRMZYXvyneg\n\t"
                      "andi	$15, $15, 4095\n\t"
                      ".LRMZYXvyneg:\n\t"
                      "sll	$24, $15, 2\n\t"
                      "lui	$25, %%hi(D_800523F0)\n\t"
                      "addu	$25, $25, $24\n\t"
                      "lw	$25, %%lo(D_800523F0)($25)\n\t"
                      "nop\n\t"
                      "sll	$14, $25, 16\n\t"
                      "sra	$14, $14, 16\n\t"
                      "negu	$12, $14\n\t"
                      "j	.LRMZYXvyjoin\n\t"
                      "sra	$9, $25, 16\n\t"
                      ".LRMZYXvypos:\n\t"
                      "sll	$24, $25, 2\n\t"
                      "lui	$25, %%hi(D_800523F0)\n\t"
                      "addu	$25, $25, $24\n\t"
                      "lw	$25, %%lo(D_800523F0)($25)\n\t"
                      "nop\n\t"
                      "sll	$14, $25, 16\n\t"
                      "sra	$12, $14, 16\n\t"
                      "negu	$14, $12\n\t"
                      "sra	$9, $25, 16\n\t"
                      ".LRMZYXvyjoin:\n\t"
                      "multu	$11, $9\n\t"
                      "lh	$15, 4($4)\n\t"
                      "sh	$14, 12($5)\n\t"
                      "mflo	$24\n\t"
                      "sra	$14, $24, 12\n\t"
                      "nop\n\t"
                      "multu	$8, $9\n\t"
                      "sh	$14, 14($5)\n\t"
                      "bgez	$15, .LRMZYXvzpos\n\t"
                      "andi	$25, $15, 4095\n\t"
                      "mflo	$24\n\t"
                      "sra	$14, $24, 12\n\t"
                      "sh	$14, 16($5)\n\t"
                      "negu	$15, $15\n\t"
                      "bgez	$15, .LRMZYXvzneg\n\t"
                      "andi	$15, $15, 4095\n\t"
                      ".LRMZYXvzneg:\n\t"
                      "sll	$24, $15, 2\n\t"
                      "lui	$25, %%hi(D_800523F0)\n\t"
                      "addu	$25, $25, $24\n\t"
                      "lw	$25, %%lo(D_800523F0)($25)\n\t"
                      "nop\n\t"
                      "sll	$24, $25, 16\n\t"
                      "sra	$24, $24, 16\n\t"
                      "negu	$13, $24\n\t"
                      "j	.LRMZYXvzjoin\n\t"
                      "sra	$10, $25, 16\n\t"
                      ".LRMZYXvzpos:\n\t"
                      "mflo	$15\n\t"
                      "sra	$14, $15, 12\n\t"
                      "sh	$14, 16($5)\n\t"
                      "sll	$24, $25, 2\n\t"
                      "lui	$25, %%hi(D_800523F0)\n\t"
                      "addu	$25, $25, $24\n\t"
                      "lw	$25, %%lo(D_800523F0)($25)\n\t"
                      "nop\n\t"
                      "sll	$24, $25, 16\n\t"
                      "sra	$13, $24, 16\n\t"
                      "sra	$10, $25, 16\n\t"
                      ".LRMZYXvzjoin:\n\t"
                      "multu	$9, $10\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo	$15\n\t"
                      "sra	$14, $15, 12\n\t"
                      "sh	$14, 0($5)\n\t"
                      "multu	$13, $9\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo	$15\n\t"
                      "sra	$14, $15, 12\n\t"
                      "nop\n\t"
                      "multu	$11, $12\n\t"
                      "sh	$14, 6($5)\n\t"
                      "nop\n\t"
                      "mflo	$15\n\t"
                      "sra	$24, $15, 12\n\t"
                      "nop\n\t"
                      "multu	$24, $10\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo	$15\n\t"
                      "sra	$14, $15, 12\n\t"
                      "nop\n\t"
                      "multu	$13, $8\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo	$15\n\t"
                      "sra	$25, $15, 12\n\t"
                      "subu	$15, $14, $25\n\t"
                      "multu	$8, $10\n\t"
                      "sh	$15, 2($5)\n\t"
                      "nop\n\t"
                      "mflo	$14\n\t"
                      "sra	$15, $14, 12\n\t"
                      "nop\n\t"
                      "multu	$24, $13\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo	$14\n\t"
                      "sra	$25, $14, 12\n\t"
                      "addu	$14, $25, $15\n\t"
                      "multu	$12, $8\n\t"
                      "sh	$14, 8($5)\n\t"
                      "nop\n\t"
                      "mflo	$15\n\t"
                      "sra	$24, $15, 12\n\t"
                      "nop\n\t"
                      "multu	$24, $10\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo	$15\n\t"
                      "sra	$14, $15, 12\n\t"
                      "nop\n\t"
                      "multu	$11, $13\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo	$15\n\t"
                      "sra	$25, $15, 12\n\t"
                      "addu	$15, $14, $25\n\t"
                      "multu	$11, $10\n\t"
                      "sh	$15, 4($5)\n\t"
                      "nop\n\t"
                      "mflo	$14\n\t"
                      "sra	$15, $14, 12\n\t"
                      "nop\n\t"
                      "multu	$24, $13\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo	$14\n\t"
                      "sra	$25, $14, 12\n\t"
                      "subu	$14, $25, $15\n\t"
                      "sh	$14, 10($5)\n\t"
                      ".set\treorder"
                      : "=r"(pRet) : : "$8", "$9", "$10", "$11", "$12", "$13",
                          "$14", "$15", "$24", "$25", "memory");
    return pRet;
}
