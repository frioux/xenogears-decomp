// RotMatrixX on: RotMatrixZYX (the function before it) carries one tail pad word
// in retail, so the four bytes at 0x3B648 are an `asm` subsegment in
// config/slus_006.64.yaml and this file covers 0x3B64C-0x3B7E4. See
// psyq/libgte_average_b.

extern long D_800523F0[]; // one entry per 1/4096 turn, (cos << 16) | sin

/* Sony's vector.s, transcribed like ScaleMatrix: gcc emits `mult` (not the
   original's `multu`), never merges the trig lookup's sign handling, and reads
   the table through its own registers, so a C body scores 15.53%. The original
   masks the angle before the sign test picks the branch and negates sin in the
   negative branch (RotMatrixY negates in the positive one), and pulls sin and
   cos out of the single table word with sll/sra and sra. */
MATRIX *RotMatrixX(long r, MATRIX *m) {
    register MATRIX *pRet __asm__("$2");

    __asm__ volatile (".set\tnoreorder\n\t"
                      "addu\t$15, $4, $0\n\t"
                      "addu\t$2, $5, $0\n\t"
                      "bgez\t$15, .LRMXpos\n\t"
                      "andi\t$25, $15, 4095\n\t"
                      "negu\t$15, $15\n\t"
                      "bgez\t$15, .LRMXneg\n\t"
                      "andi\t$15, $15, 4095\n\t"
                      ".LRMXneg:\n\t"
                      "sll\t$24, $15, 2\n\t"
                      "lui\t$25, %%hi(D_800523F0)\n\t"
                      "addu\t$25, $25, $24\n\t"
                      "lw\t$25, %%lo(D_800523F0)($25)\n\t"
                      "nop\n\t"
                      "sll\t$14, $25, 16\n\t"
                      "sra\t$14, $14, 16\n\t"
                      "negu\t$9, $14\n\t"
                      "j\t.LRMXjoin\n\t"
                      "sra\t$8, $25, 16\n\t"
                      ".LRMXpos:\n\t"
                      "sll\t$24, $25, 2\n\t"
                      "lui\t$25, %%hi(D_800523F0)\n\t"
                      "addu\t$25, $25, $24\n\t"
                      "lw\t$25, %%lo(D_800523F0)($25)\n\t"
                      "nop\n\t"
                      "sll\t$24, $25, 16\n\t"
                      "sra\t$9, $24, 16\n\t"
                      "sra\t$8, $25, 16\n\t"
                      ".LRMXjoin:\n\t"
                      "lh\t$10, 6($5)\n\t"
                      "lh\t$13, 12($5)\n\t"
                      "multu\t$8, $10\n\t"
                      "lh\t$11, 8($5)\n\t"
                      "lh\t$14, 14($5)\n\t"
                      "mflo\t$24\n\t"
                      "lh\t$12, 10($5)\n\t"
                      "lh\t$15, 16($5)\n\t"
                      "multu\t$9, $13\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo\t$25\n\t"
                      "subu\t$25, $24, $25\n\t"
                      "sra\t$24, $25, 12\n\t"
                      "multu\t$8, $11\n\t"
                      "sh\t$24, 6($5)\n\t"
                      "nop\n\t"
                      "mflo\t$24\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "multu\t$9, $14\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo\t$25\n\t"
                      "subu\t$25, $24, $25\n\t"
                      "sra\t$24, $25, 12\n\t"
                      "multu\t$8, $12\n\t"
                      "sh\t$24, 8($5)\n\t"
                      "nop\n\t"
                      "mflo\t$24\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "multu\t$9, $15\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo\t$25\n\t"
                      "subu\t$25, $24, $25\n\t"
                      "sra\t$24, $25, 12\n\t"
                      "multu\t$9, $10\n\t"
                      "sh\t$24, 10($5)\n\t"
                      "nop\n\t"
                      "mflo\t$24\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "multu\t$8, $13\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo\t$25\n\t"
                      "addu\t$25, $24, $25\n\t"
                      "sra\t$24, $25, 12\n\t"
                      "multu\t$9, $11\n\t"
                      "sh\t$24, 12($5)\n\t"
                      "nop\n\t"
                      "mflo\t$24\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "multu\t$8, $14\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo\t$25\n\t"
                      "addu\t$25, $24, $25\n\t"
                      "sra\t$24, $25, 12\n\t"
                      "multu\t$9, $12\n\t"
                      "sh\t$24, 14($5)\n\t"
                      "nop\n\t"
                      "mflo\t$24\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "multu\t$8, $15\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo\t$25\n\t"
                      "addu\t$25, $24, $25\n\t"
                      "sra\t$24, $25, 12\n\t"
                      "sh\t$24, 16($5)\n\t"
                      ".set\treorder"
                      : "=r"(pRet) : : "$8", "$9", "$10", "$11", "$12", "$13",
                          "$14", "$15", "$24", "$25", "memory");
    return pRet;
}
