// RotMatrixZ on: RotMatrixY (the function before it) carries two tail pad words
// in retail, so the eight bytes at 0x3B984 are an `asm` subsegment in
// config/slus_006.64.yaml and this file covers 0x3B98C-0x3BB24. See
// psyq/libgte_average_c.

extern long D_800523F0[]; // one entry per 1/4096 turn, (cos << 16) | sin

/* Sony's vector.s, transcribed like RotMatrixX: gcc emits `mult` where the
   original has `multu` and reads the trig table through its own registers.
   RotMatrixZ is RotMatrixX's body with every matrix offset six lower (row 0 at
   0/2/4, row 1 at 6/8/10). */
MATRIX *RotMatrixZ(long r, MATRIX *m) {
    register MATRIX *pRet __asm__("$2");

    __asm__ volatile (".set\tnoreorder\n\t"
                      "addu\t$15, $4, $0\n\t"
                      "addu\t$2, $5, $0\n\t"
                      "bgez\t$15, .LRMZpos\n\t"
                      "andi\t$25, $15, 4095\n\t"
                      "negu\t$15, $15\n\t"
                      "bgez\t$15, .LRMZneg\n\t"
                      "andi\t$15, $15, 4095\n\t"
                      ".LRMZneg:\n\t"
                      "sll\t$24, $15, 2\n\t"
                      "lui\t$25, %%hi(D_800523F0)\n\t"
                      "addu\t$25, $25, $24\n\t"
                      "lw\t$25, %%lo(D_800523F0)($25)\n\t"
                      "nop\n\t"
                      "sll\t$14, $25, 16\n\t"
                      "sra\t$14, $14, 16\n\t"
                      "negu\t$9, $14\n\t"
                      "j\t.LRMZjoin\n\t"
                      "sra\t$8, $25, 16\n\t"
                      ".LRMZpos:\n\t"
                      "sll\t$24, $25, 2\n\t"
                      "lui\t$25, %%hi(D_800523F0)\n\t"
                      "addu\t$25, $25, $24\n\t"
                      "lw\t$25, %%lo(D_800523F0)($25)\n\t"
                      "nop\n\t"
                      "sll\t$24, $25, 16\n\t"
                      "sra\t$9, $24, 16\n\t"
                      "sra\t$8, $25, 16\n\t"
                      ".LRMZjoin:\n\t"
                      "lh\t$10, 0($5)\n\t"
                      "lh\t$13, 6($5)\n\t"
                      "multu\t$8, $10\n\t"
                      "lh\t$11, 2($5)\n\t"
                      "lh\t$14, 8($5)\n\t"
                      "mflo\t$24\n\t"
                      "lh\t$12, 4($5)\n\t"
                      "lh\t$15, 10($5)\n\t"
                      "multu\t$9, $13\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo\t$25\n\t"
                      "subu\t$25, $24, $25\n\t"
                      "sra\t$24, $25, 12\n\t"
                      "multu\t$8, $11\n\t"
                      "sh\t$24, 0($5)\n\t"
                      "nop\n\t"
                      "mflo\t$24\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "multu\t$9, $14\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo\t$25\n\t"
                      "subu\t$25, $24, $25\n\t"
                      "sra\t$24, $25, 12\n\t"
                      "multu\t$8, $12\n\t"
                      "sh\t$24, 2($5)\n\t"
                      "nop\n\t"
                      "mflo\t$24\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "multu\t$9, $15\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo\t$25\n\t"
                      "subu\t$25, $24, $25\n\t"
                      "sra\t$24, $25, 12\n\t"
                      "multu\t$9, $10\n\t"
                      "sh\t$24, 4($5)\n\t"
                      "nop\n\t"
                      "mflo\t$24\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "multu\t$8, $13\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo\t$25\n\t"
                      "addu\t$25, $24, $25\n\t"
                      "sra\t$24, $25, 12\n\t"
                      "multu\t$9, $11\n\t"
                      "sh\t$24, 6($5)\n\t"
                      "nop\n\t"
                      "mflo\t$24\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "multu\t$8, $14\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo\t$25\n\t"
                      "addu\t$25, $24, $25\n\t"
                      "sra\t$24, $25, 12\n\t"
                      "multu\t$9, $12\n\t"
                      "sh\t$24, 8($5)\n\t"
                      "nop\n\t"
                      "mflo\t$24\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "multu\t$8, $15\n\t"
                      "nop\n\t"
                      "nop\n\t"
                      "mflo\t$25\n\t"
                      "addu\t$25, $24, $25\n\t"
                      "sra\t$24, $25, 12\n\t"
                      "sh\t$24, 10($5)\n\t"
                      ".set\treorder"
                      : "=r"(pRet) : : "$8", "$9", "$10", "$11", "$12", "$13",
                          "$14", "$15", "$24", "$25", "memory");
    return pRet;
}

