// The tail of Psy-Q libgte from LightColor on. AverageSZ4 (the function before
// it) carries three pad words in retail -- the shipped .OBJ pads every function's
// tail to a 16-byte multiple -- and they are the `asm` subsegment at 0x3AB30 in
// config/slus_006.64.yaml, which this file starts after at 0x3AB3C.

void LightColor(VECTOR *v0, VECTOR *v1) {
    gte_ldlvl(v0);
    gte_nop();
    gte_lc_b();
    gte_stlvl(v1);
}

void DpqColorLight(VECTOR *v0, CVECTOR *v1, long p, CVECTOR *v2) {
    gte_ldlvl(v0);
    gte_ldrgb(v1);
    gte_lddp_a2(p);
    gte_nop();
    gte_dpcl_b();
    gte_strgb(v2);
}


void DpqColor3(CVECTOR *v0, CVECTOR *v1, CVECTOR *v2, long p, CVECTOR *v3,
               CVECTOR *v4, CVECTOR *v5) {
    gte_ldrgb3(v0, v1, v2);
    gte_lddp(p);
    gte_nop();
    gte_dpct_b();
    gte_strgb3_stack(v3, v4, v5);
}

void Intpl(VECTOR *v0, long p, CVECTOR *v1) {
    gte_ldlvl(v0);
    gte_lddp(p);
    gte_nop();
    gte_intpl_b();
    gte_strgb(v1);
}

