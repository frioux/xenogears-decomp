// The tail of Psy-Q libgte from RotTransSV on. Lzc (the function before it)
// carries one pad word in retail -- the shipped .OBJ pads every function's tail
// to a 16-byte multiple -- and it is the `asm` subsegment at 0x3AD48 in
// config/slus_006.64.yaml, which this file starts after at 0x3AD4C.

void RotTransSV(SVECTOR *v0, SVECTOR *v1, long *flag) {
    long f;

    gte_ldv0(v0);
    gte_nop();
    gte_mvmva_b(1, 0, 0, 0, 0);
    gte_stsv(v1);
    gte_stflg_val(f);
    *flag = f;
}

SVECTOR *SquareSS12(SVECTOR *v0, SVECTOR *v1) {
    gte_ldsv(v0);
    gte_nop();
    gte_sqr12_b();
    gte_stsv(v1);
    return v1;
}

