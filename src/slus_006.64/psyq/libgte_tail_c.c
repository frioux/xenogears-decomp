// The last of the pad slices of Psy-Q's libgte tail: SetMulMatrix and
// ApplyRotMatrixLV. It is its own translation unit only because ScaleMatrixL
// (the function before SetMulMatrix) carries three pad words in retail -- the
// shipped .OBJ pads every function's tail to a 16-byte multiple -- and the twelve
// bytes at 0x3A070 are the `asm` subsegment in config/slus_006.64.yaml;
// 0x3A2C4 is ApplyRotMatrixLV's own pad, which starts psyq/libgte_mulmatrix.
// Transcribed as the asm Sony wrote; see psyq/libgte_tail for the rules.

MATRIX *SetMulMatrix(MATRIX *m0, MATRIX *m1) {
    register MATRIX *pRet __asm__("$2");

    __asm__ volatile (".set\tnoreorder\n\t"
                      "lw\t$8, 0($4)\n\t"
                      "lw\t$9, 4($4)\n\t"
                      "lw\t$10, 8($4)\n\t"
                      "lw\t$11, 12($4)\n\t"
                      "lw\t$12, 16($4)\n\t"
                      "ctc2\t$8, $0\n\t"
                      "ctc2\t$9, $1\n\t"
                      "ctc2\t$10, $2\n\t"
                      "ctc2\t$11, $3\n\t"
                      "ctc2\t$12, $4\n\t"
                      "lhu\t$8, 0($5)\n\t"
                      "lw\t$9, 4($5)\n\t"
                      "lw\t$10, 12($5)\n\t"
                      "lui\t$at, 65535\n\t"
                      "and\t$9, $9, $at\n\t"
                      "or\t$8, $8, $9\n\t"
                      "mtc2\t$8, $0\n\t"
                      "mtc2\t$10, $1\n\t"
                      "nop\n\t"
                      ".word\t0x4a486012\n\t"
                      "lhu\t$8, 2($5)\n\t"
                      "lw\t$9, 8($5)\n\t"
                      "lh\t$10, 14($5)\n\t"
                      "sll\t$9, $9, 16\n\t"
                      "or\t$8, $8, $9\n\t"
                      "mfc2\t$11, $9\n\t"
                      "mfc2\t$12, $10\n\t"
                      "mfc2\t$13, $11\n\t"
                      "mtc2\t$8, $0\n\t"
                      "mtc2\t$10, $1\n\t"
                      "nop\n\t"
                      ".word\t0x4a486012\n\t"
                      "lhu\t$8, 4($5)\n\t"
                      "lw\t$9, 8($5)\n\t"
                      "lw\t$10, 16($5)\n\t"
                      "lui\t$at, 65535\n\t"
                      "and\t$9, $9, $at\n\t"
                      "or\t$8, $8, $9\n\t"
                      "mfc2\t$14, $9\n\t"
                      "mfc2\t$15, $10\n\t"
                      "mfc2\t$24, $11\n\t"
                      "mtc2\t$8, $0\n\t"
                      "mtc2\t$10, $1\n\t"
                      "nop\n\t"
                      ".word\t0x4a486012\n\t"
                      "andi\t$11, $11, 65535\n\t"
                      "sll\t$14, $14, 16\n\t"
                      "or\t$14, $14, $11\n\t"
                      "andi\t$13, $13, 65535\n\t"
                      "sll\t$24, $24, 16\n\t"
                      "or\t$24, $24, $13\n\t"
                      "mfc2\t$8, $9\n\t"
                      "mfc2\t$9, $10\n\t"
                      "mfc2\t$10, $11\n\t"
                      "andi\t$8, $8, 65535\n\t"
                      "sll\t$12, $12, 16\n\t"
                      "or\t$8, $8, $12\n\t"
                      "andi\t$15, $15, 65535\n\t"
                      "sll\t$9, $9, 16\n\t"
                      "or\t$9, $9, $15\n\t"
                      "ctc2\t$14, $0\n\t"
                      "ctc2\t$8, $1\n\t"
                      "ctc2\t$9, $2\n\t"
                      "ctc2\t$24, $3\n\t"
                      "ctc2\t$10, $4\n\t"
                      "addu\t$2, $4, $0\n\t"
                      ".set\treorder"
                      : "=r"(pRet) : : "$1", "$8", "$9", "$10", "$11", "$12", "$13",
                          "$14", "$15", "$24", "memory");
    return pRet;
}

/* The rotation-matrix twin of ApplyMatrixLV: the same split of each 32-bit
   component into a 15-bit fraction (masked, into IR) and its overflow (into IR
   as the second pass), two MVMVAs against the matrix already in the GTE, and
   the magnitude-preserving <<3 on the way back out. Transcribed for the same
   reason as ApplyMatrixLV; the unreachable `sra` after the second `b` is Sony's
   own, retail carries it in ApplyMatrixLV too. */
VECTOR *ApplyRotMatrixLV(VECTOR *v0, VECTOR *v1) {
    register VECTOR *pRet __asm__("$5");

    __asm__ volatile (".set\tnoreorder\n\t"
                      "lw\t$8, 0($4)\n\t"
                      "lw\t$9, 4($4)\n\t"
                      "lw\t$10, 8($4)\n\t"
                      "bgez\t$8, .L800499BC\n\t"
                      "sra\t$11, $8, 15\n\t"
                      "negu\t$8, $8\n\t"
                      "sra\t$11, $8, 15\n\t"
                      "andi\t$8, $8, 32767\n\t"
                      "negu\t$11, $11\n\t"
                      "b\t.L800499C0\n\t"
                      "negu\t$8, $8\n\t"
                      "sra\t$11, $8, 15\n\t"
                      ".L800499BC:\n\t"
                      "andi\t$8, $8, 32767\n\t"
                      ".L800499C0:\n\t"
                      "bgez\t$9, .L800499E4\n\t"
                      "sra\t$12, $9, 15\n\t"
                      "negu\t$9, $9\n\t"
                      "sra\t$12, $9, 15\n\t"
                      "andi\t$9, $9, 32767\n\t"
                      "negu\t$12, $12\n\t"
                      "b\t.L800499E8\n\t"
                      "negu\t$9, $9\n\t"
                      "sra\t$12, $9, 15\n\t"
                      ".L800499E4:\n\t"
                      "andi\t$9, $9, 32767\n\t"
                      ".L800499E8:\n\t"
                      "bgez\t$10, .L80049A0C\n\t"
                      "sra\t$13, $10, 15\n\t"
                      "negu\t$10, $10\n\t"
                      "sra\t$13, $10, 15\n\t"
                      "andi\t$10, $10, 32767\n\t"
                      "negu\t$13, $13\n\t"
                      "b\t.L80049A10\n\t"
                      "negu\t$10, $10\n\t"
                      "sra\t$13, $10, 15\n\t"
                      ".L80049A0C:\n\t"
                      "andi\t$10, $10, 32767\n\t"
                      ".L80049A10:\n\t"
                      "mtc2\t$11, $9\n\t"
                      "mtc2\t$12, $10\n\t"
                      "mtc2\t$13, $11\n\t"
                      "nop\n\t"
                      ".word\t0x4a41e012\n\t"
                      "mfc2\t$11, $25\n\t"
                      "mfc2\t$12, $26\n\t"
                      "mfc2\t$13, $27\n\t"
                      "mtc2\t$8, $9\n\t"
                      "mtc2\t$9, $10\n\t"
                      "mtc2\t$10, $11\n\t"
                      "nop\n\t"
                      ".word\t0x4a49e012\n\t"
                      "bgez\t$11, .L80049A5C\n\t"
                      "nop\n\t"
                      "negu\t$11, $11\n\t"
                      "sll\t$11, $11, 3\n\t"
                      "b\t.L80049A60\n\t"
                      "negu\t$11, $11\n\t"
                      ".L80049A5C:\n\t"
                      "sll\t$11, $11, 3\n\t"
                      ".L80049A60:\n\t"
                      "bgez\t$12, .L80049A78\n\t"
                      "nop\n\t"
                      "negu\t$12, $12\n\t"
                      "sll\t$12, $12, 3\n\t"
                      "b\t.L80049A7C\n\t"
                      "negu\t$12, $12\n\t"
                      ".L80049A78:\n\t"
                      "sll\t$12, $12, 3\n\t"
                      ".L80049A7C:\n\t"
                      "bgez\t$13, .L80049A94\n\t"
                      "nop\n\t"
                      "negu\t$13, $13\n\t"
                      "sll\t$13, $13, 3\n\t"
                      "b\t.L80049A98\n\t"
                      "negu\t$13, $13\n\t"
                      ".L80049A94:\n\t"
                      "sll\t$13, $13, 3\n\t"
                      ".L80049A98:\n\t"
                      "mfc2\t$8, $25\n\t"
                      "mfc2\t$9, $26\n\t"
                      "mfc2\t$10, $27\n\t"
                      "addu\t$8, $8, $11\n\t"
                      "addu\t$9, $9, $12\n\t"
                      "addu\t$10, $10, $13\n\t"
                      "sw\t$8, 0($5)\n\t"
                      "sw\t$9, 4($5)\n\t"
                      "sw\t$10, 8($5)\n\t"
                      ".set\treorder"
                      : "=r"(pRet) : : "$8", "$9", "$10", "$11", "$12", "$13",
                          "memory");
    return pRet;
}
