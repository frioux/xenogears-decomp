// The tail of Psy-Q's libgte after TransMatrix and ScaleMatrix: SetRotMatrix on.
// It is its own translation unit only because ScaleMatrix (the function before
// SetRotMatrix) carries three pad words in retail -- the shipped .OBJ pads every
// function's tail to a 16-byte multiple -- and the twelve bytes at 0x3A6F0 are
// the `asm` subsegment in config/slus_006.64.yaml. This file covers
// 0x3A6FC-0x3A8DC. Keep it one unit's worth of code with psyq/libgte_tail.

